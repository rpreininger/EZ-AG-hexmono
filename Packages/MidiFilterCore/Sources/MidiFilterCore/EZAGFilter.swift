import Foundation

/// What the filter did with an incoming event — shown in the monitor so you can see
/// *why* something did or did not reach the synth.
public enum Verdict: String, Sendable {
    /// Forwarded (possibly reshaped by the monophonic voice manager).
    case passed
    /// `Note On` classified as a fret button press and dropped.
    case suppressedFret
    /// `Note On` announced by `CC 84` — a hammer-on or pull-off, not a struck note.
    case suppressedHammerOn
    /// `Note Off` belonging to a `Note On` that was dropped earlier.
    case swallowedNoteOff
    /// Channel outside the merge range.
    case filteredChannel
    /// `Note On` held back, waiting to see whether its `Note Off` arrives (blip mode).
    case heldForBlip
    /// `Note Off` of a sounding note held back, waiting to see whether a fret note
    /// follows and turns it into a fingering change (slide mode).
    case heldForSlide
    /// A fret change that retuned the ringing note instead of being dropped.
    case slid
    /// A held `Note On` and its `Note Off` cancelled each other out (blip mode).
    case droppedBlipPair
    /// Non-note message dropped because pass-through is off.
    case droppedOther

    public var isSuppression: Bool {
        switch self {
        case .passed: return false
        case .heldForBlip: return false
        case .heldForSlide: return false
        case .slid: return false
        default: return true
        }
    }

    public var displayName: String {
        switch self {
        case .passed: return "→"
        case .suppressedFret: return "Bund"
        case .suppressedHammerOn: return "Hammer-On"
        case .swallowedNoteOff: return "Off verworfen"
        case .filteredChannel: return "Kanal"
        case .heldForBlip: return "wartet"
        case .heldForSlide: return "wartet"
        case .slid: return "Rutsch"
        case .droppedBlipPair: return "kurz"
        case .droppedOther: return "andere"
        }
    }
}

/// Merges the EZ-AG's six string channels onto one channel, drops the notes generated by
/// the fret buttons, and reduces what is left to a single voice for a monophonic synth.
///
/// The class is not thread safe by itself; the CoreMIDI layer serialises access.
public final class EZAGFilter {

    public struct Result {
        public var out: [MIDIEvent]
        public var verdict: Verdict

        init(_ out: [MIDIEvent], _ verdict: Verdict) {
            self.out = out
            self.verdict = verdict
        }
    }

    // MARK: State

    private struct PendingNote {
        var event: MIDIEvent
        var deadline: Double
    }

    private struct PendingOff {
        var note: UInt8
        var deadline: Double
    }

    private struct StringState {
        /// Notes whose `Note On` was dropped — their `Note Off` has to go as well.
        var suppressed: Set<UInt8> = []
        /// Notes currently held down according to the *input*.
        var held: Set<UInt8> = []
        /// When each note was last switched off, for retrigger detection.
        var lastNoteOff: [UInt8: Double] = [:]
        /// Blip mode: `Note On` waiting for its verdict.
        var pending: [UInt8: PendingNote] = [:]
        /// Slide mode: the release of the sounding note, held back for a breath to see
        /// whether a fret note follows and makes it a fingering change.
        var pendingOff: PendingOff?
        /// When `CC 84` last announced a hammer-on or pull-off on this string.
        var lastPortamento: Double?
        /// A suppressed hammer-on is followed by the `Note Off` of the note it replaced.
        /// Swallowing that too is what keeps the struck note ringing.
        var legatoGuardUntil: Double?
    }

    /// Portamento control — the EZ-AG sends this right before every hammer-on and
    /// pull-off, carrying the note the transition starts from.
    private static let portamentoControl: UInt8 = 84

    private struct HeldNote {
        var channel: UInt8
        var source: UInt8
        var out: UInt8
        var velocity: UInt8
    }

    public private(set) var config: FilterConfig
    private var strings = [StringState](repeating: StringState(), count: 16)
    private var stack: [HeldNote] = []
    private var sounding: HeldNote?
    /// Semitones the output channel is currently bent by — a slide leaves it standing
    /// until something new is struck.
    private var bend = 0

    public init(config: FilterConfig = FilterConfig()) {
        self.config = config
    }

    /// Applies a new configuration. Returns the events needed to avoid a stuck note when
    /// the output channel or the transposition changes underneath a sounding note.
    @discardableResult
    public func setConfig(_ newValue: FilterConfig) -> [MIDIEvent] {
        let old = config
        var flush: [MIDIEvent] = []
        let needsFlush = old.outputChannel != newValue.outputChannel
            || old.transpose != newValue.transpose
            || old.monophonic != newValue.monophonic
        if needsFlush, let sounding {
            flush.append(MIDIEvent(channel: old.outputChannel,
                                   message: .noteOff(note: sounding.out, velocity: 0)))
            if bend != 0 {
                flush.append(MIDIEvent(channel: old.outputChannel, message: .pitchBend(value: 8192)))
                bend = 0
            }
            self.sounding = nil
            stack.removeAll()
        }
        config = newValue
        return flush
    }

    /// Drops all state without emitting anything.
    public func reset() {
        strings = [StringState](repeating: StringState(), count: 16)
        stack.removeAll()
        sounding = nil
        bend = 0
    }

    /// Everything off on the output channel.
    public func panic() -> [MIDIEvent] {
        var out: [MIDIEvent] = []
        if let sounding {
            out.append(MIDIEvent(channel: config.outputChannel,
                                 message: .noteOff(note: sounding.out, velocity: 0)))
        }
        out.append(MIDIEvent(channel: config.outputChannel, message: .pitchBend(value: 8192)))
        out.append(MIDIEvent(channel: config.outputChannel, message: .controlChange(controller: 123, value: 0)))
        reset()
        return out
    }

    // MARK: Processing

    public func process(_ event: MIDIEvent) -> Result {
        guard config.inputChannelRange.contains(event.channel) else {
            switch config.otherChannels {
            case .drop: return Result([], .filteredChannel)
            case .passThrough: return Result([event], .passed)
            }
        }

        switch event.message {
        case let .noteOn(note, velocity):
            return noteOn(note: note, velocity: velocity, event: event)
        case let .noteOff(note, _):
            return noteOff(note: note, event: event)

        case let .controlChange(controller, _) where controller == Self.portamentoControl:
            strings[Int(event.channel)].lastPortamento = event.time
            // Passing it on would make a portamento capable synth glide to a note we are
            // about to throw away.
            guard !config.suppressHammerOns else { return Result([], .suppressedHammerOn) }
            guard config.passOtherMessages else { return Result([], .droppedOther) }
            return forwarded(event)

        default:
            guard config.passOtherMessages else { return Result([], .droppedOther) }
            return forwarded(event)
        }
    }

    private func forwarded(_ event: MIDIEvent) -> Result {
        var copy = event
        copy.channel = config.outputChannel
        return Result([copy], .passed)
    }

    /// Drives the two modes that need a clock. Call regularly (a few milliseconds) while
    /// `fretMode == .blip` or `fretSlide` is on; returns the `Note On`s that have outlived
    /// the blip window and count as real plucks, plus the releases no fret note claimed.
    public func tick(now: Double) -> [MIDIEvent] {
        var out: [MIDIEvent] = []
        if config.fretMode == .blip {
            for channel in strings.indices {
                guard !strings[channel].pending.isEmpty else { continue }
                for (note, pending) in strings[channel].pending where pending.deadline <= now {
                    strings[channel].pending.removeValue(forKey: note)
                    guard case let .noteOn(_, velocity) = pending.event.message else { continue }
                    out += emitNoteOn(channel: UInt8(channel), note: note, velocity: velocity)
                }
            }
        }
        if config.fretSlide {
            for channel in strings.indices {
                guard let pendingOff = strings[channel].pendingOff,
                      pendingOff.deadline <= now else { continue }
                // Nothing followed — it really was a release, only a few milliseconds late.
                strings[channel].pendingOff = nil
                out += emitNoteOff(channel: UInt8(channel), note: pendingOff.note)
            }
        }
        return out
    }

    /// True while something is waiting on the clock — a blip verdict or a held release —
    /// so the engine knows it has to keep ticking.
    public var hasPendingNotes: Bool {
        strings.contains { !$0.pending.isEmpty || $0.pendingOff != nil }
    }

    // MARK: Note handling

    private func noteOn(note: UInt8, velocity: UInt8, event: MIDIEvent) -> Result {
        let channel = Int(event.channel)
        let stringWasSilent = strings[channel].held.isEmpty
        strings[channel].held.insert(note)

        if let announced = strings[channel].lastPortamento, config.suppressHammerOns,
           (event.time - announced) * 1000 <= config.hammerOnWindowMs {
            strings[channel].lastPortamento = nil
            // A release held back for a possible slide belongs to the note this hammer-on
            // replaces. Dropping it here is what keeps the struck note ringing.
            strings[channel].pendingOff = nil
            // The instrument releases the note this one replaces a moment later; swallow
            // that release too, so the struck note plays on through the fingering change.
            strings[channel].legatoGuardUntil = event.time + config.hammerOnWindowMs / 1000

            // Never mark the note that is actually sounding — its real release has to get
            // through, otherwise it hangs forever.
            let isTheSoundingNote = sounding?.channel == event.channel && sounding?.source == note
            if !isTheSoundingNote {
                strings[channel].suppressed.insert(note)
            }
            return Result([], .suppressedHammerOn)
        }

        if let pendingOff = strings[channel].pendingOff {
            strings[channel].pendingOff = nil
            if isFretPress(note: note, velocity: velocity, event: event,
                           stringWasSilent: stringWasSilent) {
                // The string never stopped ringing — the player only moved the fingering.
                return Result(slide(channel: event.channel, from: pendingOff.note, to: note), .slid)
            }
            // Not a fingering change after all: the note really ended and this is the next
            // pluck. Let the held release out first, then treat the pluck as usual.
            var out = emitNoteOff(channel: event.channel, note: pendingOff.note)
            out += emitNoteOn(channel: event.channel, note: note, velocity: velocity)
            return Result(out, .passed)
        }

        if isFretPress(note: note, velocity: velocity, event: event, stringWasSilent: stringWasSilent) {
            strings[channel].suppressed.insert(note)
            return Result([], .suppressedFret)
        }

        if config.fretMode == .blip {
            strings[channel].pending[note] = PendingNote(event: event,
                                                         deadline: event.time + config.blipMaxMs / 1000)
            return Result([], .heldForBlip)
        }

        return Result(emitNoteOn(channel: event.channel, note: note, velocity: velocity), .passed)
    }

    private func noteOff(note: UInt8, event: MIDIEvent) -> Result {
        let channel = Int(event.channel)
        strings[channel].held.remove(note)
        // Recorded even for suppressed notes: the `Note Off` of a fret note is exactly the
        // marker that lets the following pluck through in retrigger mode.
        strings[channel].lastNoteOff[note] = event.time

        if strings[channel].suppressed.remove(note) != nil {
            return Result([], .swallowedNoteOff)
        }
        if strings[channel].pending.removeValue(forKey: note) != nil {
            return Result([], .droppedBlipPair)
        }
        // The release that belongs to a hammer-on we just threw away.
        if let guardUntil = strings[channel].legatoGuardUntil, event.time <= guardUntil {
            strings[channel].legatoGuardUntil = nil
            return Result([], .swallowedNoteOff)
        }

        // Slide mode: a fingering change starts with the release of the note that is
        // ringing, and the fret note follows half a millisecond later. Hold the release
        // just long enough to tell the two apart.
        if config.fretSlide, config.monophonic, canDetectFretPress,
           let current = sounding, current.channel == event.channel, current.source == note,
           strings[channel].pendingOff == nil {
            strings[channel].pendingOff = PendingOff(note: note,
                                                     deadline: event.time + config.slideWindowMs / 1000)
            return Result([], .heldForSlide)
        }

        return Result(emitNoteOff(channel: event.channel, note: note), .passed)
    }

    /// Sliding needs the fret detection to be able to answer at all — without it every
    /// held release would simply be handed on late.
    private var canDetectFretPress: Bool {
        config.fretMode == .velocity || config.fretMode == .retrigger
    }

    /// 14 bit, centre 8192. Deliberately integer arithmetic — the firmware does the same
    /// and both have to land on exactly the same value.
    private func bendValue(semitones: Int) -> UInt16 {
        let span = Int(max(1, config.pitchBendRange))
        let value = 8192 + (semitones * 8192) / span
        return UInt16(max(0, min(16383, value)))
    }

    /// A slide leaves the channel bent. Before anything new is struck it has to go back
    /// to the centre, otherwise the new note inherits the old one's detune.
    private func centredBend() -> [MIDIEvent] {
        guard bend != 0 else { return [] }
        bend = 0
        return [MIDIEvent(channel: config.outputChannel, message: .pitchBend(value: 8192))]
    }

    /// A fingering change on a ringing string: the pitch moves, the strike keeps its
    /// velocity, and the envelope is not retriggered.
    private func slide(channel: UInt8, from old: UInt8, to new: UInt8) -> [MIDIEvent] {
        guard let current = sounding, current.channel == channel, current.source == old else {
            // The voice moved to another string while the release was held — there is
            // nothing ringing here to retune, so the fret note stays a fret note.
            strings[Int(channel)].suppressed.insert(new)
            return []
        }

        let target = transposed(new)

        // The note is already sounding — moving it is a pitch bend, not a new note. The
        // envelope is never touched, which is exactly what a slide sounds like.
        if config.slideUsesPitchBend {
            let interval = Int(target) - Int(current.out)
            if abs(interval) <= Int(max(1, config.pitchBendRange)) {
                bend = interval
                stack.removeAll { $0.channel == channel && ($0.source == old || $0.source == new) }
                // Same voice, same note on the wire: only the fingering it answers to
                // changes, so the release of *that* is what ends the note.
                var slid = current
                slid.source = new
                stack.append(slid)
                sounding = slid
                return [MIDIEvent(channel: config.outputChannel,
                                  message: .pitchBend(value: bendValue(semitones: interval)))]
            }
        }

        // Further than the synth can bend: a real note change, with the bend centred
        // first — a retriggered note is better than a wrong pitch.
        var out = centredBend()
        stack.removeAll { $0.channel == channel && ($0.source == old || $0.source == new) }
        // The pluck's velocity carries over: it is still that strike sounding, only at a
        // different pitch.
        let slid = HeldNote(channel: channel, source: new, out: target, velocity: current.velocity)
        stack.append(slid)
        sounding = slid

        guard target != current.out else { return out }
        // New note first, then release the old one, so a mono synth glides instead of
        // retriggering its envelope.
        out.append(MIDIEvent(channel: config.outputChannel,
                             message: .noteOn(note: target, velocity: current.velocity)))
        out.append(MIDIEvent(channel: config.outputChannel,
                             message: .noteOff(note: current.out, velocity: 0)))
        return out
    }

    private func isFretPress(note: UInt8, velocity: UInt8, event: MIDIEvent, stringWasSilent: Bool) -> Bool {
        switch config.fretMode {
        case .off, .blip:
            return false
        case .velocity:
            return config.velocityExactMatch ? velocity == config.velocityThreshold
                                             : velocity <= config.velocityThreshold
        case .retrigger:
            let channel = Int(event.channel)
            if let off = strings[channel].lastNoteOff[note],
               (event.time - off) * 1000 <= config.retriggerWindowMs {
                return false // Note Off → Note On: a pluck on a sounding string
            }
            // A lone Note On. Either a fret press, or the very first pluck of a string
            // that was not sounding at all.
            return !(config.allowFirstNoteOnIdleString && stringWasSilent)
        }
    }

    // MARK: Monophonic voice manager

    private func emitNoteOn(channel: UInt8, note: UInt8, velocity: UInt8) -> [MIDIEvent] {
        let out = transposed(note)
        guard config.monophonic else {
            return centredBend()
                + [MIDIEvent(channel: config.outputChannel, message: .noteOn(note: out, velocity: velocity))]
        }
        stack.removeAll { $0.channel == channel && $0.source == note }
        let attacked = HeldNote(channel: channel, source: note, out: out, velocity: velocity)
        stack.append(attacked)
        return updateVoice(attacked: attacked)
    }

    private func emitNoteOff(channel: UInt8, note: UInt8) -> [MIDIEvent] {
        guard config.monophonic else {
            return [MIDIEvent(channel: config.outputChannel, message: .noteOff(note: transposed(note), velocity: 0))]
        }
        let wasSounding = sounding?.channel == channel && sounding?.source == note
        stack.removeAll { $0.channel == channel && $0.source == note }

        guard config.fallbackToHeldNote else {
            // Only what the player struck last is allowed to sound. Releasing it ends the
            // note; notes still held on other strings stay silent until struck again.
            guard wasSounding, let old = sounding else { return [] }
            sounding = nil
            return [MIDIEvent(channel: config.outputChannel, message: .noteOff(note: old.out, velocity: 0))]
        }

        // The released note may not have been the sounding one; the voice then simply
        // stays where it is, or falls back to another note still held down.
        return updateVoice(attacked: nil)
    }

    /// Brings the single output voice in line with the current note stack. `attacked` is
    /// the note the player just hit, if any — only that one may re-trigger the voice.
    private func updateVoice(attacked: HeldNote?) -> [MIDIEvent] {
        let channel = config.outputChannel
        let winner = pickWinner(attacked: attacked)
        var out: [MIDIEvent] = []

        switch (sounding, winner) {
        case (nil, nil):
            break

        case let (.some(old), nil):
            out.append(MIDIEvent(channel: channel, message: .noteOff(note: old.out, velocity: 0)))
            sounding = nil

        case let (nil, .some(new)):
            out += centredBend()
            out.append(MIDIEvent(channel: channel, message: .noteOn(note: new.out, velocity: new.velocity)))
            sounding = new

        case let (.some(old), .some(new)):
            if old.out == new.out {
                // Same pitch. Only re-attack when the player hit this very note again —
                // not when some other string merely joined the stack behind it.
                let struckAgain = attacked.map { $0.channel == new.channel && $0.source == new.source } ?? false
                if struckAgain && config.retriggerSameNote {
                    out.append(MIDIEvent(channel: channel, message: .noteOff(note: old.out, velocity: 0)))
                    out += centredBend()
                    out.append(MIDIEvent(channel: channel, message: .noteOn(note: new.out, velocity: new.velocity)))
                }
                sounding = new
            } else if config.legato {
                // New note first so a mono synth in legato mode glides instead of
                // retriggering its envelope.
                out += centredBend()
                out.append(MIDIEvent(channel: channel, message: .noteOn(note: new.out, velocity: new.velocity)))
                out.append(MIDIEvent(channel: channel, message: .noteOff(note: old.out, velocity: 0)))
                sounding = new
            } else {
                out.append(MIDIEvent(channel: channel, message: .noteOff(note: old.out, velocity: 0)))
                out += centredBend()
                out.append(MIDIEvent(channel: channel, message: .noteOn(note: new.out, velocity: new.velocity)))
                sounding = new
            }
        }
        return out
    }

    private func pickWinner(attacked: HeldNote?) -> HeldNote? {
        // Without fallback there is no returning to a held note, so the priority has
        // nothing left to decide: whatever was struck last takes the voice. Otherwise a
        // held high note would silently swallow every lower note played after it.
        if !config.fallbackToHeldNote, let attacked { return attacked }

        switch config.priority {
        case .last: return stack.last
        case .highest: return stack.max { $0.out < $1.out }
        case .lowest: return stack.min { $0.out < $1.out }
        }
    }

    private func transposed(_ note: UInt8) -> UInt8 {
        UInt8(max(0, min(127, Int(note) + config.transpose)))
    }
}
